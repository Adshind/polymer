<script>
document.addEventListener('DOMContentLoaded', function () {
    const form = document.getElementById('polymerContactForm');
    const submitBtn = document.getElementById('contactSubmitBtn');
    const btnText = document.getElementById('contactBtnText');
    const btnSpinner = document.getElementById('contactBtnSpinner');
    const successAlert = document.getElementById('rfqSuccessAlert');
    const refIdSpan = document.getElementById('rfqRefId');

    if (form) {
        form.addEventListener('submit', function (e) {
            e.preventDefault();

            const name = document.getElementById('contactName').value.trim();
            const phone = document.getElementById('contactPhone').value.trim();
            const email = document.getElementById('contactEmail').value.trim();

            if (!name || !phone || !email) {
                alert('Please fill out all required fields marked with an asterisk (*).');
                return;
            }

            submitBtn.disabled = true;
            btnText.innerHTML = '<i class="fa-solid fa-spinner fa-spin me-2"></i> Submitting...';
            btnSpinner.style.display = 'inline-block';

            setTimeout(function () {
                const randomCode = 'PP-RFQ-' + Math.floor(100000 + Math.random() * 900000);
                if (refIdSpan) refIdSpan.textContent = randomCode;

                submitBtn.disabled = false;
                btnText.innerHTML = '<i class="fa-solid fa-paper-plane me-2"></i> Submit Inquiry / Request RFQ';
                btnSpinner.style.display = 'none';

                if (successAlert) {
                    successAlert.style.display = 'block';
                    successAlert.scrollIntoView({ behavior: 'smooth', block: 'center' });
                }

                form.reset();
            }, 800);
        });
    }
});
</script>

